#!/usr/bin/env bash
# setup.sh — install the calendar-sync daemon (Apple Calendar <-> Google).
#   setup.sh                  build the reader + writer, build the host app if it is missing, install the agent
#   setup.sh --plist-only     reinstall the agent only (keeps the binaries and the host app)
#   setup.sh --rebuild-host   rebuild the host app, then reinstall the agent. A rebuild changes the app's
#                             ad-hoc signature, so macOS asks again for Calendar + Documents access.
#   setup.sh --build-host     (re)build the host app only, agent unchanged — to test it before switching
#   setup.sh --terminal-host  fallback: run each tick in a Terminal window that closes itself (uses
#                             Terminal's grants; for when the host app can't get its own)
set -euo pipefail
REPO="${CALSYNC_REPO:-$HOME/Documents/GitHub/AO-Personal-OS}"
HERE="$REPO/automations/calendar-sync"
LABEL="com.user.calendar-sync"
MODE="${1:-}"
HOST_APP="$HOME/Applications/CalendarSync.app"
HOST_LOG="$HOME/Library/Logs/calendar-sync/host.log"

mkdir -p "$HERE/.work/state" "$(dirname "$HOST_LOG")"
chmod +x "$HERE/run.sh" "$HERE/setup.sh" 2>/dev/null || true

if [ -z "$MODE" ]; then
  echo "[setup] building the EventKit reader + writer..."
  swiftc "$HERE/ss_cal_read.swift" -o "$HERE/.work/ss-cal-read"
  swiftc "$HERE/ss_cal_write.swift" -o "$HERE/.work/ss-cal-write"   # reverse leg: SS 'Busy' placeholders
fi

# --- host app ----------------------------------------------------------------------------
# EventKit and ~/Documents are TCC-protected, and a plain launchd process is denied both. Until
# 2026-11-19 each tick ran in a new Terminal window to borrow Terminal's grants; the windows popped
# up on every run and piled up (335). The host is a faceless AppleScript applet (LSUIElement: no
# window, no Dock icon) that gets its own Calendar + Documents grants from two prompts on its first
# run; run.sh and everything it starts inherit them. It lives outside ~/Documents so launchd can
# start it, logs outside ~/Documents so a lost Documents grant still leaves a trace, and posts a
# macOS notification when a run fails. PATH matches Terminal's (Homebrew python3, not /usr/bin's 3.9).
build_host() {
  local src="$HERE/.work/host.applescript" ip="$HOST_APP/Contents/Info.plist" pb=/usr/libexec/PlistBuddy
  local why="calendar-sync reads your SoftServe calendar and writes Busy blocks into it."
  cat > "$src" <<EOF
-- calendar-sync host: one tick, no window. Generated by setup.sh; edit there, not here.
on run
	set logf to "$HOST_LOG"
	set cmd to "export PATH=/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin LANG=en_US.UTF-8; " & quoted form of "$HERE/run.sh" & " daemon >> " & quoted form of logf & " 2>&1"
	try
		do shell script cmd
	on error errMsg
		try
			do shell script "echo " & quoted form of ((do shell script "date +%FT%T") & " host: run.sh failed: " & errMsg) & " >> " & quoted form of logf
		end try
		display notification "The sync run failed. Details: ~/Library/Logs/calendar-sync/host.log" with title "calendar-sync"
	end try
end run
EOF
  rm -rf "$HOST_APP"
  mkdir -p "$(dirname "$HOST_APP")"
  osacompile -o "$HOST_APP" "$src"
  for k in CFBundleIdentifier LSUIElement NSCalendarsFullAccessUsageDescription NSCalendarsUsageDescription; do
    "$pb" -c "Delete :$k" "$ip" 2>/dev/null || true   # the applet template may or may not carry each key
  done
  "$pb" -c "Add :CFBundleIdentifier string com.user.calendar-sync.host" "$ip"
  "$pb" -c "Add :LSUIElement bool true" "$ip"
  "$pb" -c "Add :NSCalendarsFullAccessUsageDescription string $why" "$ip"
  "$pb" -c "Add :NSCalendarsUsageDescription string $why" "$ip"
  codesign --force --deep --sign - "$HOST_APP"
  echo "[setup] built $HOST_APP: its first run asks for Calendar and Documents access; allow both"
}
if [ "$MODE" != "--terminal-host" ] && { [ "$MODE" = "--rebuild-host" ] || [ "$MODE" = "--build-host" ] || [ ! -d "$HOST_APP" ]; }; then
  build_host
fi
[ "$MODE" = "--build-host" ] && { echo "[setup] agent unchanged; test with: open -g -j -W \"$HOST_APP\""; exit 0; }

# --- what each tick runs -----------------------------------------------------------------
xml() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }
PROGRAM=()
if [ "$MODE" = "--terminal-host" ]; then
  # Terminal fallback: the AppleScript waits for the run's shell to exit, then closes that window
  # (the Basic profile keeps windows after exit). Inline (-e), so osascript never reads ~/Documents.
  APPLESCRIPT=(
    'tell application "Terminal"'
    "set t to do script \"$HERE/run.sh daemon; exit\""
    'set theTTY to ""'
    'try'
    'set theTTY to tty of t'
    'end try'
    'set wid to missing value'
    'repeat with w in windows'
    'try'
    'if tty of tab 1 of w is theTTY then'
    'set wid to id of w'
    'exit repeat'
    'end if'
    'end try'
    'end repeat'
    'repeat 300 times'
    'delay 3'
    'try'
    'if (count of (processes of t)) is 0 then exit repeat'
    'on error'
    'exit repeat'
    'end try'
    'end repeat'
    'set outcome to "window not found"'
    'try'
    'if wid is not missing value then'
    'if (count of (processes of t)) is 0 then'
    'close window id wid'
    'set outcome to "closed window " & wid'
    'else'
    'set outcome to "left window " & wid & " open: run still busy"'
    'end if'
    'end if'
    'on error errMsg'
    'set outcome to "close failed: " & errMsg'
    'end try'
    'end tell'
    'return (do shell script "date +%FT%T") & " " & outcome'   # -> launchd.out.log
  )
  # Check before replacing anything: an AppleScript that doesn't compile would fail every tick
  # with nothing but a line in launchd.err.log.
  OSA_ARGS=(); for line in "${APPLESCRIPT[@]}"; do OSA_ARGS+=(-e "$line"); done
  osacompile -o "$HERE/.work/launch-check.scpt" "${OSA_ARGS[@]}" || { echo "[setup] AppleScript does not compile — agent left unchanged"; exit 1; }
  rm -f "$HERE/.work/launch-check.scpt"
  PROGRAM=(/usr/bin/osascript "${OSA_ARGS[@]}")
  HOSTED_BY="a Terminal window that closes itself"
else
  [ -d "$HOST_APP" ] || { echo "[setup] $HOST_APP is missing — agent left unchanged"; exit 1; }
  PROGRAM=(/usr/bin/open -g -j -W "$HOST_APP")   # -W: launchd sees the run's real duration
  HOSTED_BY="the faceless host app, no window"
fi

# --- launchd plist: every 30 minutes (:00 and :30), Mon-Fri, on the Mac's local clock ----
# (Alex works with Europe and the US at once from SF; run.sh gates out stray weekend ticks.
#  Every 30 minutes since 2026-11-24, hourly before.)
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
mkdir -p "$HOME/Library/LaunchAgents"
{
  echo '<?xml version="1.0" encoding="UTF-8"?>'
  echo '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">'
  echo '<plist version="1.0"><dict>'
  echo "  <key>Label</key><string>$LABEL</string>"
  echo '  <key>ProgramArguments</key><array>'
  for arg in "${PROGRAM[@]}"; do printf '    <string>%s</string>\n' "$(xml "$arg")"; done
  echo '  </array>'
  echo '  <key>StartCalendarInterval</key><array>'
  for d in 1 2 3 4 5; do   # no Hour key = every hour of that weekday, at :00 and at :30
    for m in 0 30; do
      echo "    <dict><key>Weekday</key><integer>$d</integer><key>Minute</key><integer>$m</integer></dict>"
    done
  done
  echo '  </array>'
  echo "  <key>StandardOutPath</key><string>$HERE/.work/launchd.out.log</string>"
  echo "  <key>StandardErrorPath</key><string>$HERE/.work/launchd.err.log</string>"
  echo '</dict></plist>'
} > "$PLIST.new"
plutil -lint "$PLIST.new" >/dev/null || { echo "[setup] generated plist is invalid — agent left unchanged"; rm -f "$PLIST.new"; exit 1; }
mv "$PLIST.new" "$PLIST"

launchctl bootout "gui/$(id -u)" "$PLIST" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"

echo "[setup] installed launchd agent: $LABEL  (every 30 minutes Mon-Fri on the Mac's local clock, via $HOSTED_BY)"
[ -n "$MODE" ] && exit 0

cat <<EOF

ONE-TIME GOOGLE SETUP (only you can do this — it's your account):
  1) console.cloud.google.com -> create/select a project
  2) APIs & Services -> Library -> enable "Google Calendar API"
  3) APIs & Services -> OAuth consent screen -> External -> add yourself as a Test user,
     THEN set "Publishing status" to "In production" (Publish app). This is important:
     a "Testing" app expires the refresh token every 7 days; a published one does not.
     (You'll see an "unverified app" warning at sign-in once -> Advanced -> proceed.)
  4) Credentials -> Create credentials -> OAuth client ID -> "Desktop app" -> copy the Client ID + Secret
  5) store them in Keychain:
       security add-generic-password -U -a "\$USER" -s CALSYNC_GOOGLE_CLIENT_ID     -w '<client id>'
       security add-generic-password -U -a "\$USER" -s CALSYNC_GOOGLE_CLIENT_SECRET -w '<client secret>'
  6) authorize once (opens a browser):
       source "$HERE/config.sh" && python3 -I "$HERE/gcal.py" auth

THEN TEST + GO LIVE:
  source "$HERE/config.sh" && "$HERE/run.sh" now        # DRY-RUN: prints the plan, no writes
  touch "$HERE/.work/state/LIVE"                          # flip to live writes
  open -g -j -W "$HOST_APP"                               # first real sync: allow the two prompts

Logs:      $HOST_LOG  ·  $HERE/.work/state/run-log.jsonl
Uninstall: launchctl bootout "gui/\$(id -u)" "$PLIST"
EOF
